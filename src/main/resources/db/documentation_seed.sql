### Recherche vectorielle

Panneau extensible permettant une recherche semantique dans le vector store :
- **Texte de recherche** : requete en langage naturel
- **Top K** : nombre de resultats souhaites (defaut : 10)
- **Resultats** : tableau avec ID (8 premiers chars), Contenu (tronque a 400 chars), Metadata (cles)

La recherche utilise la **similarite cosine** via pgvector pour trouver les documents les plus proches du texte saisi.

### Backup DB

Cree un dump PostgreSQL via `pg_dump` dans `/tmp/`. Le resultat affiche le chemin du fichier et sa taille en KB. Les credentials sont extraits automatiquement de la DataSource Spring (aucun hardcoding).

